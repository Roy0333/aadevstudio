/** Dark or white icon, whichever reads better on the brand colour. */
export function iconForeground(hex: string) {
  const [r, g, b] = [0, 2, 4].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255);
  const luminance = 0.2126 * r + 0.7152 * g + 0.0722 * b;
  return luminance > 0.6 ? "#191a23" : "#ffffff";
}
